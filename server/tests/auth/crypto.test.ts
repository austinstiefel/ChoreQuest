import { SignJWT, decodeJwt } from "jose";
import { afterEach, describe, expect, it, vi } from "vitest";
import { hashPassword, hashPin, verifyPassword, verifyPin } from "../../src/auth/passwords.js";
import {
	createAccessToken,
	createRefreshToken,
	decodeAccessToken,
	decodeRefreshToken,
} from "../../src/auth/tokens.js";
import type { AuthConfig } from "../../src/config/auth.js";

const TEST_SECRET = "phase3b-test-secret-at-least-16";
const OTHER_SECRET = "different-phase3b-test-secret";
const config: AuthConfig = {
	secretKey: TEST_SECRET,
	accessTokenExpireMinutes: 15,
	refreshTokenExpireDays: 30,
	cookieSecure: false,
	corsOrigins: [],
};
const encoder = new TextEncoder();

afterEach(() => {
	vi.useRealTimers();
});

describe("bcrypt password and PIN utilities", () => {
	it("hashes and verifies newly-created password and PIN hashes", async () => {
		const passwordHash = await hashPassword("PasswordForNode42");
		const pinHash = await hashPin("123456");

		expect(passwordHash).toMatch(/^\$2[aby]\$12\$/);
		expect(pinHash).toMatch(/^\$2[aby]\$12\$/);
		await expect(verifyPassword("PasswordForNode42", passwordHash)).resolves.toBe(true);
		await expect(verifyPassword("wrong-password", passwordHash)).resolves.toBe(false);
		await expect(verifyPin("123456", pinHash)).resolves.toBe(true);
		await expect(verifyPin("654321", pinHash)).resolves.toBe(false);
	});

	it("verifies a fixed bcrypt hash generated by Python bcrypt.gensalt()", async () => {
		const pythonHash = "$2b$12$ErDH5SaN3etIrCH966/o3uvc2baZ7zUjafKNTu8LJgfitNGPlYaOG";

		await expect(verifyPassword("PythonFixturePassword42", pythonHash)).resolves.toBe(true);
		await expect(verifyPassword("not-the-python-password", pythonHash)).resolves.toBe(false);
	});
});

describe("HS256 token utilities", () => {
	it("creates Python-compatible access and refresh payloads with configured lifetimes", async () => {
		vi.useFakeTimers();
		vi.setSystemTime(new Date("2030-01-02T03:04:05.000Z"));
		const now = 1_893_553_445;

		const accessToken = await createAccessToken(42, "admin", config);
		const refreshToken = await createRefreshToken(42, config);

		expect(decodeJwt(accessToken)).toEqual({
			sub: "42",
			role: "admin",
			exp: now + 15 * 60,
			type: "access",
		});
		expect(decodeJwt(refreshToken)).toEqual({
			sub: "42",
			exp: now + 30 * 86_400,
			type: "refresh",
		});
		await expect(decodeAccessToken(accessToken, config)).resolves.toMatchObject({
			sub: "42",
			role: "admin",
			type: "access",
		});
		await expect(decodeRefreshToken(refreshToken, config)).resolves.toMatchObject({
			sub: "42",
			type: "refresh",
		});
	});

	it("verifies a fixed JWT generated by the Python HS256 implementation", async () => {
		const pythonToken =
			"eyJhbGciOiAiSFMyNTYiLCAidHlwIjogIkpXVCJ9.eyJzdWIiOiAiNDIiLCAicm9sZSI6ICJhZG1pbiIsICJleHAiOiA0MTAyNDQ0ODAwLCAidHlwZSI6ICJhY2Nlc3MifQ.Kh-4ZE3L4hT7ux-g25CDMLXUwA8B-CIO6Zq371WvDIg";

		await expect(decodeAccessToken(pythonToken, config)).resolves.toEqual({
			sub: "42",
			role: "admin",
			exp: 4_102_444_800,
			type: "access",
		});
	});

	it("rejects invalid signatures, expired tokens, malformed tokens, unsupported algorithms, and wrong types", async () => {
		const accessToken = await createAccessToken(1, "kid", config);
		const refreshToken = await createRefreshToken(1, config);
		const otherConfig = { ...config, secretKey: OTHER_SECRET };
		const expiredToken = await new SignJWT({ role: "admin", type: "access", exp: 1 })
			.setProtectedHeader({ alg: "HS256", typ: "JWT" })
			.setSubject("1")
			.sign(encoder.encode(TEST_SECRET));
		const unsupportedAlgorithm = `${Buffer.from(JSON.stringify({ alg: "none", typ: "JWT" })).toString("base64url")}.${Buffer.from(JSON.stringify({ sub: "1", exp: 4_102_444_800, type: "access", role: "admin" })).toString("base64url")}.`;

		await expect(decodeAccessToken(accessToken, otherConfig)).resolves.toBeNull();
		await expect(decodeAccessToken(expiredToken, config)).resolves.toBeNull();
		await expect(decodeAccessToken("not-a-jwt", config)).resolves.toBeNull();
		await expect(decodeAccessToken(unsupportedAlgorithm, config)).resolves.toBeNull();
		await expect(decodeAccessToken(refreshToken, config)).resolves.toBeNull();
		await expect(decodeRefreshToken(accessToken, config)).resolves.toBeNull();
	});
});
